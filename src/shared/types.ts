  courses: Course[];
  lessons: Lesson[];
  sources: Source[];
  findings: Finding[];
  checks: CheckRun[];
  schedules: any[];
  subscription: any;
  usage: { used: number; limit: number; reset: string };
  configuration: { checks: boolean; billing: boolean; email: boolean };
